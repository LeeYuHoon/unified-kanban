def write_transcript(root, rel="proj-demo/session-a.jsonl", extra_lines=()):
    """Write the canonical fixture, plus malformed/blank lines, and return its path."""
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = []
    for i, rec in enumerate(records()):
        lines.append(json.dumps(rec))
        if i == 3:
            lines.append("")  # blank line: ignored, not counted as malformed
            lines.append("{not json at all")  # malformed
    lines.extend(extra_lines)
    # truncated trailing record, as happens when a session is still being written
    lines.append('{"type":"assistant","message":{"role":"assistant","content":[{"typ')
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return path


