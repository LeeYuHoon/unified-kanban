def _user(content, ts, **extra):
    rec = {
        "type": "user",
        "uuid": extra.pop("uuid", "u-%s" % ts),
        "sessionId": SESSION_ID,
        "cwd": CWD,
        "timestamp": ts,
        "message": {"role": "user", "content": content},
    }
    rec.update(extra)
    return rec


def _assistant(content, ts, stop_reason="end_turn", **extra):
    rec = {
        "type": "assistant",
        "uuid": extra.pop("uuid", "a-%s" % ts),
        "sessionId": SESSION_ID,
        "cwd": CWD,
        "timestamp": ts,
        "message": {
            "role": "assistant",
            "model": "claude-opus-5",
            "content": content,
            "stop_reason": stop_reason,
        },
    }
    rec.update(extra)
    return rec


